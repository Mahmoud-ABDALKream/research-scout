import fs from "fs/promises";
import path from "path";
import { SCORE_THRESHOLD, scoutDir } from "./config";
import { AuditEntry, HistoryEntry, ScoutRunResult } from "./types";

async function ensureDir() {
  await fs.mkdir(scoutDir(), { recursive: true });
}

export async function persistRun(result: ScoutRunResult) {
  await ensureDir();
  const dir = scoutDir();

  const audit = {
    run_timestamp: result.timestamp,
    candidates_fetched: result.candidatesFetched,
    candidates_read: result.candidatesRead,
    candidates_qualified: result.candidatesQualified,
    new_roles: result.newRoles,
    threshold: result.threshold,
    sources: result.sources,
    entries: result.audit,
  };
  await fs.writeFile(path.join(dir, "audit_log.json"), JSON.stringify(audit, null, 2));

  const capture = result.log.join("\n") + "\n\n--- DIGEST ---\n" + result.digest;
  await fs.writeFile(path.join(dir, "run_capture.txt"), capture);

  const historyEntry: HistoryEntry = {
    date: result.timestamp.slice(0, 10),
    timestamp: result.timestamp,
    candidates_fetched: result.candidatesFetched,
    candidates_read: result.candidatesRead,
    candidates_qualified: result.candidatesQualified,
    digest: result.digest,
    qualified_roles: result.qualified,
  };
  await fs.appendFile(
    path.join(dir, "history.jsonl"),
    JSON.stringify(historyEntry) + "\n"
  );

  const d = new Date(result.timestamp);
  const email = `Subject: Research Scout Daily Digest — ${d.toLocaleDateString("en-US", { month: "short", day: "2-digit", year: "numeric" })}
To: mahmoudabdelkreambusiness@gmail.com
From: Research Scout <scout@agent.local>
Date: ${d.toUTCString()}

${result.digest}

───
This digest was generated by the Research Scout agent.
Audit log: agent_mvp/audit_log.json
Run timestamp: ${result.timestamp}
`;
  await fs.writeFile(path.join(dir, "digest_email.txt"), email);
  await fs.writeFile(path.join(dir, "last_result.json"), JSON.stringify(result, null, 2));
}

export async function loadHistory(): Promise<HistoryEntry[]> {
  try {
    const raw = await fs.readFile(path.join(scoutDir(), "history.jsonl"), "utf8");
    return raw
      .split("\n")
      .map((l) => l.trim())
      .filter(Boolean)
      .map((l) => JSON.parse(l) as HistoryEntry);
  } catch {
    return [];
  }
}

export async function seenUrls(): Promise<Set<string>> {
  const history = await loadHistory();
  const urls = new Set<string>();
  for (const e of history) {
    for (const r of e.qualified_roles || []) {
      if (r.url) urls.add(r.url);
    }
  }
  return urls;
}

